/** In Arabic only, wrap a value in Unicode isolates (U+2068 … U+2069) for a
 *  shared template whose Arabic does not isolate its placeholder itself. */
export function isolate(language: string, v: string): string {
  return language === 'ar' ? `⁨${v}⁩` : v
}

/** A translated template whose placeholders are React nodes (a <code>, a
 *  <bdi>), so a sentence keeps its own word order in each language instead of
 *  being glued from fragments. `t` must be called with `{name}` left in place:
 *  pass each key as its own `{key}`. */
export function richNodes(template: string, nodes: Record<string, ReactNode>): ReactNode {
  const parts = template.split(/\{(\w+)\}/)
  return createElement(Fragment, null, ...parts.map((p, i) =>
    i % 2 ? createElement(Fragment, { key: i }, p in nodes ? nodes[p] : `{${p}}`) : p))
}
