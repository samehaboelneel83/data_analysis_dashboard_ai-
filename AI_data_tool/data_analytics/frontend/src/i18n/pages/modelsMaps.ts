/**
 * 8-i18n: the modelsMaps area's words, in English and Arabic. Spread into en.ts /
 * ar.ts. Keys start with "pg.modelsMaps." and the two objects hold the same keys.
 *
 * The English texts are byte-identical to the literals they replaced (tests
 * find them by that text). In Arabic a name in a plain string sits inside «»
 * and Unicode isolates (U+2068 ... U+2069); in JSX the caller hands `rich` a
 * <bdi> for it instead.
 *
 * The model families ("random forest" ...) are the server's codes. They are
 * already words in English, so English shows the code as it is; only the
 * label is translated, never the code that is sent back.
 */

/** Arabic counted nouns: "صف واحد", "صفّان", "3 صفوف", "11 صفًا", "100 صف". */
const arCount = (v: string, one: string, two: string, few: string, many: string, other: string) =>
  `{${v}, plural, zero{# ${other}} one{${one}} two{${two}} few{# ${few}} many{# ${many}} other{# ${other}}}`
const arRows = (v: string) => arCount(v, 'صف واحد', 'صفّان', 'صفوف', 'صفًا', 'صف')

