/** `t(key)` with some placeholders filled by React nodes (a link, a <code>, a
 *  <strong>), so a sentence that holds markup is still one whole template a
 *  translator can reorder. Plain-string vars are interpolated as usual. */
export function nodesT(t: TranslateFn, key: MessageKey, nodes: Record<string, ReactNode>,
                       vars: Record<string, string | number> = {}): ReactNode {
  const marked: Record<string, string | number> = { ...vars }
  for (const k of Object.keys(nodes)) marked[k] = `\u0001${k}\u0002`
  const parts = t(key, marked).split(/\u0001(\w+)\u0002/)
  return createElement(Fragment, null, ...parts.map((p, i) =>
    i % 2 ? createElement(Fragment, { key: i }, nodes[p]) : p))
}
